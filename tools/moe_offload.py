"""Можно ли запустить GLM-5.3 на ПК с RTX 5070 Ti: расчёт памяти и скорости для MoE с выгрузкой экспертов.

Идея: видеокарта не обязана хранить всю модель. В MoE на каждый токен работает малая доля весов.
Внимание и общие слои живут в VRAM, а «эксперты» — в оперативной памяти (или на NVMe).
Скорость ограничена тем, сколько байт экспертов надо прочитать на токен.

python tools/moe_offload.py
"""
GB = 1e9

models = {
    # имя: (всего параметров, активных на токен, примерно на GPU: внимание + общие слои + эмбеддинги)
    "GLM-5.3": (753e9, 40e9, 12e9),
    "GLM-5.3-Flash": (321e9, 18e9, 6e9),
    "GLM-4.7-Flash": (31e9, 3.5e9, 1.5e9),
}
bits_options = [4.5, 3.0, 2.5, 2.0]
memories = {
    "DDR5, 2 канала (обычный ПК)": 80,
    "DDR5, 4 канала (HEDT)": 160,
    "NVMe PCIe 5.0 (с диска)": 12,
}

print("16 ГБ видеопамяти = 128 Гбит. На 753 млрд параметров это 0.17 бита на параметр.")
print("Известные методы держат качество примерно до 2–3 бит, ниже 1 бита модель разрушается.")
print("Значит, «вся модель целиком в VRAM без потерь» — нет. Но вся модель в VRAM и не нужна.\n")

for name, (total, active, gpu_part) in models.items():
    print(f"=== {name}: {total / 1e9:.0f} млрд всего, ~{active / 1e9:.0f} млрд активных на токен ===")
    for bits in bits_options:
        size = total * bits / 8 / GB
        gpu = gpu_part * bits / 8 / GB
        routed = (active - gpu_part) * bits / 8 / GB        # байт экспертов на токен
        line = f"  {bits:.1f} бит: вся модель {size:6.0f} ГБ, на GPU {gpu:4.1f} ГБ, эксперты на токен {routed:4.1f} ГБ →"
        speeds = []
        for mname, bw in memories.items():
            speeds.append(f"{bw / routed:5.1f} ток/с ({mname.split(' (')[0]})")
        print(line, "; ".join(speeds))
    print()

print("Ускорители поверх этого (известные методы, складываются):")
print("  • кэш «горячих» экспертов в свободной VRAM: эксперты используются неравномерно (+20–50%)")
print("  • предсказание экспертов следующего слоя и предзагрузка, пока считается текущий")
print("  • спекулятивное декодирование: маленькая модель пишет черновик, большая проверяет пачку токенов разом (×1.5–2.5)")
