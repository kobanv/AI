"""Оценки бюджета вычислений и памяти для архитектуры «Ткань» на RTX 5070 Ti.

Все числа — порядки величин (back-of-envelope), а не бенчмарки.
Запуск: python tools/budget.py
"""

YEAR = 365 * 24 * 3600

# --- Железо ---------------------------------------------------------------
GPU = {
    "name": "RTX 5070 Ti",
    "vram_gb": 16,
    "bw_gbs": 896,            # GDDR7, 256 бит
    "l2_mb": 48,
    "bf16_dense_tflops": 176, # тензорные ядра, dense (FP32-аккумуляция на GeForce может быть вдвое ниже)
    "train_eff_tflops": 50,   # реалистично достижимо при обучении (~30-40% MFU)
}
CPU = {"name": "CPU, DDR5 2 канала", "bw_gbs": 80}

def fmt(x):
    return f"{x:.2e}"

print("=== 1. Сколько обучения даёт одна видеокарта ===")
per_year = GPU["train_eff_tflops"] * 1e12 * YEAR
print(f"FLOP за год непрерывной работы: {fmt(per_year)}")
refs = {
    "GPT-2 124M (10B ток.)":        6 * 124e6 * 10e9,
    "TinyLlama 1.1B (3T ток.)":     6 * 1.1e9 * 3e12,
    "Llama-3 8B (15T ток.)":        6 * 8e9 * 15e12,
    "Фронтир-модель (~оценка)":     1e26,
}
for k, v in refs.items():
    print(f"  {k:30s} {fmt(v)} FLOP  = {v / per_year:10.3g} лет на 5070 Ti")

print("\n=== 2. Разрыв по данным: человек vs LLM ===")
human_words_13y = 1e8   # ~100M слов к 13 годам (предпосылка BabyLM)
llm_tokens = 1.5e13
print(f"LLM видит в ~{llm_tokens / human_words_13y:.0e} раз больше текста, чем подросток")

print("\n=== 3. Ёмкость знаний (≈2 бита/параметр, Allen-Zhu & Li) ===")
for name, params in [("ядро 1.5B", 1.5e9), ("dense 70B", 70e9),
                     ("разреженная память 32B в ОЗУ", 32e9)]:
    gb = params * 2 / 8 / 1e9
    print(f"  {name:32s} ≈ {gb:6.1f} ГБ «чистых фактов» максимум")
print("  Внешняя текстовая память (SSD 2 ТБ): ограничена только диском, обучения не требует")

print("\n=== 4. Скорость инференса (декодирование упирается в память) ===")
ridge = GPU["bf16_dense_tflops"] * 1e12 / (GPU["bw_gbs"] * 1e9)
print(f"Точка баланса GPU: {ridge:.0f} FLOP на байт; матрица×вектор при batch=1 даёт ~2 FLOP/байт")
print(f"=> при обычном декодировании вычислители простаивают ~{100 * (1 - 2 / ridge):.0f}% времени.")
print("   Значит архитектура должна тратить FLOP (циклы мысли, параллельные гипотезы), а не байты.\n")

core_params = 1.5e9
for label, bits, dev in [("GPU, ядро 8 бит", 8, GPU), ("GPU, ядро 4 бит", 4, GPU),
                         ("CPU, ядро тернарное", 2, CPU)]:
    gb = core_params * bits / 8 / 1e9
    for r in (1, 4, 16):
        cps = dev["bw_gbs"] / (gb * r)
        print(f"  {label:22s} r={r:2d} циклов: ~{cps:7.0f} чанков/с (верхняя граница)")

print("\n=== 5. Бюджет VRAM 16 ГБ ===")
vram = {
    "ядро 1.5B (8 бит)": 1.5,
    "байтовые энкодер/декодер": 0.2,
    "разреженная память (6M слотов × 1КБ)": 6.0,
    "рекуррентные состояния + окно внимания": 2.0,
    "параллельные гипотезы (batch 16) + рабочая зона": 4.0,
    "запас": 2.3,
}
for k, v in vram.items():
    print(f"  {k:48s} {v:4.1f} ГБ")
print(f"  {'ИТОГО':48s} {sum(vram.values()):4.1f} ГБ")

print("\n=== 6. Сколько токенов можно обучить за год ===")
r_fwd, k_bwd = 4, 2
flops_per_chunk = 2 * core_params * r_fwd + 4 * core_params * k_bwd
toks_year = per_year / flops_per_chunk
print(f"FLOP на чанк при обучении (r={r_fwd}, backprop через {k_bwd} цикла): {fmt(flops_per_chunk)}")
print(f"Чанков (≈токенов) за год на 5070 Ti: {fmt(toks_year)}")
print("=> с нуля это уровень ~1-3B модели на ~50-60B токенов. Отсюда вывод:")
print("   знания надо ПЕРЕСАЖИВАТЬ (дистилляция/байтификация, <1% бюджета) и ВЫНОСИТЬ во внешнюю память,")
print("   а собственный бюджет тратить на рассуждение, самопроверку и непрерывное доучивание.")

print("\n=== 7. Аренда как ускоритель (опционально) ===")
h100_eff = 400e12
hours = per_year / h100_eff / 3600
print(f"Год работы 5070 Ti ≈ {hours:.0f} часов H100 (~${hours * 2:.0f} при $2/час)")
